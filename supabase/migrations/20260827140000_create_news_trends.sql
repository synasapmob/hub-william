-- The keyword equivalent of set_news_summary, and admin-only for the same
-- reason: the route decides what to draw, this decides what is allowed.
create or replace function public.set_news_trend_summary(
  p_trend_id uuid,
  p_summary_md text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select public.is_approved_admin()) then
    raise exception 'an approved admin is required';
  end if;

  if p_summary_md is not null and length(p_summary_md) > 20000 then
    raise exception 'summary exceeds the stored length';
  end if;

  update public.news_trends
  set summary_md = p_summary_md,
      summary_status = case
        when p_summary_md is null then 'pending'::public.news_summary_status
        else 'summarized'::public.news_summary_status
      end,
      summary_model = case when p_summary_md is null then null else 'manual' end,
      summary_prompt_version = null,
      summary_error = null,
      summarized_at = case when p_summary_md is null then null else now() end,
      updated_at = now()
  where id = p_trend_id;

  if not found then
    raise exception 'news trend was not found';
  end if;
end;
$$;

revoke all on function public.set_news_trend_summary(uuid, text) from public, anon;
grant execute on function public.set_news_trend_summary(uuid, text) to authenticated;

comment on table public.news_trends is
