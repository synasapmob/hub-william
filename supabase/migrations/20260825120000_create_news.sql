-- A summary is the one field a human is expected to correct, so the browser
-- writes it directly rather than through a function. Everything else about an
-- item is derived by the collector and stays read-only.
--
-- Admin-only, and asserted here rather than trusted from the caller: the route
-- decides what to draw, this decides what is allowed.
create or replace function public.set_news_summary(
  p_item_id uuid,
  p_summary_md text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select public.is_approved_admin()) then
    raise exception 'an approved admin is required';
  end if;

  if p_summary_md is not null and length(p_summary_md) > 20000 then
    raise exception 'summary exceeds the stored length';
  end if;

  update public.news_items
  set summary_md = p_summary_md,
      summary_status = case
        when p_summary_md is null then 'extracted'::public.news_summary_status
        else 'summarized'::public.news_summary_status
      end,
      summary_model = case when p_summary_md is null then null else 'manual' end,
      summary_prompt_version = null,
      summary_error = null,
      summarized_at = case when p_summary_md is null then null else now() end,
      updated_at = now()
  where id = p_item_id;

  if not found then
    raise exception 'news item was not found';
  end if;
end;
$$;

revoke all on function public.set_news_summary(uuid, text) from public, anon;
grant execute on function public.set_news_summary(uuid, text) to authenticated;

-- private is unreachable from PostgREST, so the collector reaches it through a
-- definer function that asserts the service role, matching store_job_payloads.
create or replace function public.store_news_payloads(p_payloads jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  if jsonb_typeof(p_payloads) <> 'array' then
    raise exception 'news payloads must be an array';
  end if;

  insert into private.news_item_payloads as stored (
    item_id,
    raw_payload,
    updated_at
  )
  select
    (payload ->> 'item_id')::uuid,
    payload -> 'raw_payload',
    now()
  from jsonb_array_elements(p_payloads) as payload
  on conflict (item_id) do update
  set raw_payload = excluded.raw_payload,
      updated_at = excluded.updated_at;
end;
$$;

revoke all on function public.store_news_payloads(jsonb) from public, anon, authenticated;
grant execute on function public.store_news_payloads(jsonb) to service_role;

create or replace function public.store_news_article_text(
  p_item_id uuid,
  p_extracted_text text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  insert into private.news_article_text as stored (
    item_id,
    extracted_text,
    extracted_at
  )
  values (p_item_id, p_extracted_text, now())
  on conflict (item_id) do update
  set extracted_text = excluded.extracted_text,
      extracted_at = excluded.extracted_at;
end;
$$;

revoke all on function public.store_news_article_text(uuid, text)
  from public, anon, authenticated;
grant execute on function public.store_news_article_text(uuid, text) to service_role;

create or replace function public.read_news_article_text(p_item_id uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_text text;
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  select stored.extracted_text into v_text
  from private.news_article_text as stored
  where stored.item_id = p_item_id;

  return v_text;
end;
$$;

revoke all on function public.read_news_article_text(uuid)
  from public, anon, authenticated;
grant execute on function public.read_news_article_text(uuid) to service_role;

