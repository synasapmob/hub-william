-- The news feed: public sources collected server-side, ranked, and summarized.
--
-- Shaped after the job market deliberately. Both are "fetch public feeds, keep
-- the raw payload private, expose a normalized row under RLS, audit every run
-- per source", and the second one should not invent a second vocabulary for it.

create type public.news_category as enum ('ai', 'stack', 'genz');

create type public.news_summary_status as enum (
  'pending',
  'extracted',
  'summarized',
  'failed',
  'skipped'
);

create type public.news_sync_status as enum (
  'running',
  'succeeded',
  'partial',
  'failed'
);

create table public.news_sources (
  id text primary key,
  name text not null,
  source_type text not null,
  source_url text not null,
  -- A prior, not a verdict. Hacker News carries all three categories, so it
  -- stores null and every item is routed on its own merits. A single-topic
  -- source stores its category and sets category_exclusive so the router stops
  -- there rather than second-guessing it from a title.
  category public.news_category,
  category_exclusive boolean not null default false,
  -- Multiplies the blended score, so a low-signal firehose cannot outrank a
  -- curated feed by volume alone.
  weight numeric(3, 2) not null default 1.00
    check (weight > 0 and weight <= 2),
  enabled boolean not null default true,
  requires_secret boolean not null default false,
  last_synced_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (not category_exclusive or category is not null)
);

create table public.news_sync_runs (
  id uuid primary key default gen_random_uuid(),
  requested_by uuid not null references public.profiles (id) on delete restrict,
  status public.news_sync_status not null default 'running',
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  sources_attempted integer not null default 0 check (sources_attempted >= 0),
  sources_succeeded integer not null default 0 check (sources_succeeded >= 0),
  items_fetched integer not null default 0 check (items_fetched >= 0),
  items_created integer not null default 0 check (items_created >= 0),
  items_updated integer not null default 0 check (items_updated >= 0),
  error text
);

-- One collection at a time. A second run would double-count the attention
-- snapshots that velocity is derived from.
create unique index news_sync_runs_one_running_unique
on public.news_sync_runs ((true))
where status = 'running';

create table public.news_sync_source_runs (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.news_sync_runs (id) on delete cascade,
  source_id text not null references public.news_sources (id) on delete cascade,
  status text not null check (status in ('succeeded', 'skipped', 'failed')),
  items_fetched integer not null default 0 check (items_fetched >= 0),
  items_kept integer not null default 0 check (items_kept >= 0),
  duplicate_items integer not null default 0 check (duplicate_items >= 0),
  stop_reason text,
  error text,
  completed_at timestamptz not null default now(),
  unique (run_id, source_id)
);

create table public.news_items (
  id uuid primary key default gen_random_uuid(),
  source_id text not null references public.news_sources (id) on delete restrict,
  external_id text not null,
  url text not null,
  -- Tracking parameters stripped, host lowercased, entity families collapsed —
  -- arxiv:2608.20169 rather than four spellings of the same paper.
  canonical_url text not null,
  url_key text not null,
  title text not null,
  -- The headline reduced to comparable words. Two feeds rarely word a headline
  -- identically, so URL matching alone leaves the same story in the feed four
  -- times.
  title_key text not null default '',
  author text,
  excerpt text not null default '',
  category public.news_category not null,
  category_reason text not null default 'lexicon',
  -- The first item of a cluster owns the id every later duplicate adopts.
  cluster_id uuid not null,
  points integer check (points is null or points >= 0),
  comments integer check (comments is null or comments >= 0),
  attention numeric,
  velocity numeric,
  -- Time-independent. Decay is applied at query time, because a stored value
  -- that embeds now() is stale the moment it is written.
  hotness numeric not null default 0,
  half_life_hours numeric not null default 8 check (half_life_hours > 0),
  published_at timestamptz,
  -- published_at, clamped to first_seen_at and to at most 48h before it. A feed
  -- that backfills its archive must not repopulate the front page.
  effective_at timestamptz not null,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  summary_md text check (summary_md is null or length(summary_md) <= 20000),
  summary_model text,
  summary_prompt_version text,
  summary_status public.news_summary_status not null default 'pending',
  summary_error text,
  summarized_at timestamptz,
  content_hash text not null,
  parser_version text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source_id, external_id)
);

create index news_items_feed_idx
on public.news_items (category, hotness desc, effective_at desc);

create index news_items_url_key_idx on public.news_items (url_key);

create index news_items_cluster_idx
on public.news_items (cluster_id, hotness desc);

create index news_items_summary_queue_idx
on public.news_items (summary_status, hotness desc)
where summary_status in ('pending', 'extracted');

-- One row per item per collection. Velocity is the change between the last two,
-- which is the difference between "this is big" and "this is happening now".
create table public.news_item_metrics (
  id bigint generated by default as identity primary key,
  item_id uuid not null references public.news_items (id) on delete cascade,
  captured_at timestamptz not null default now(),
  attention numeric not null,
  unique (item_id, captured_at)
);

create index news_item_metrics_recent_idx
on public.news_item_metrics (item_id, captured_at desc);

-- Gen Z slang has no feed. The tracked half is a watchlist somebody curates,
-- and the numbers underneath it come from sources that do answer a machine.
create table public.news_watch_terms (
  id uuid primary key default gen_random_uuid(),
  term text not null,
  locale text not null default 'en' check (locale in ('en', 'vi')),
  wiki_article text,
  added_by uuid not null references public.profiles (id) on delete restrict,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (term, locale)
);

create table public.news_watch_metrics (
  id bigint generated by default as identity primary key,
  term_id uuid not null references public.news_watch_terms (id) on delete cascade,
  captured_on date not null,
  wiki_views integer check (wiki_views is null or wiki_views >= 0),
  definitions integer check (definitions is null or definitions >= 0),
  thumbs_up integer check (thumbs_up is null or thumbs_up >= 0),
  unique (term_id, captured_on)
);

create index news_watch_metrics_series_idx
on public.news_watch_metrics (term_id, captured_on desc);

create table private.news_item_payloads (
  item_id uuid primary key references public.news_items (id) on delete cascade,
  raw_payload jsonb not null,
  updated_at timestamptz not null default now(),
  check (jsonb_typeof(raw_payload) = 'object')
);

-- Article bodies are fetched from the open web and are the input a summarizing
-- model reads, which makes them prompt-injection carriers. They stay in the
-- schema the browser has no grants on, and only the extract the model needs is
-- kept.
create table private.news_article_text (
  item_id uuid primary key references public.news_items (id) on delete cascade,
  extracted_text text not null,
  extracted_at timestamptz not null default now()
);

