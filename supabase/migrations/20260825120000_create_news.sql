-- The same pair of questions is_approved_user answers, plus the one the watch
-- list needs: approval opens the workspace, the role decides who may change
-- what everyone else sees.
create or replace function public.is_approved_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and status = 'approved'
      and role = 'admin'
  );
$$;

revoke all on function public.is_approved_admin() from public;
grant execute on function public.is_approved_admin() to authenticated;

