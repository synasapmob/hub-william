create type public.ai_provider as enum ('openai', 'anthropic', 'google');
create type public.provider_connection_method as enum ('admin_key', 'oauth', 'collector');
create type public.provider_connection_status as enum (
  'verifying',
  'connected',
  'needs_attention',
  'disconnected'
);
create type public.usage_cost_type as enum ('reported', 'estimated');

create table public.provider_connections (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  provider public.ai_provider not null,
  connection_method public.provider_connection_method not null,
  status public.provider_connection_status not null default 'verifying',
  display_name text not null,
  external_account_id text,
  email text,
  workspace_name text,
  history_starts_at timestamptz not null,
  capabilities jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  last_synced_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (jsonb_typeof(capabilities) = 'object'),
  check (jsonb_typeof(metadata) = 'object')
);

create table public.usage_buckets (
  id bigint generated by default as identity primary key,
  connection_id uuid not null references public.provider_connections (id) on delete cascade,
  period_start timestamptz not null,
  period_end timestamptz not null,
  model text not null default 'unknown',
  input_tokens bigint not null default 0 check (input_tokens >= 0),
  output_tokens bigint not null default 0 check (output_tokens >= 0),
  cached_input_tokens bigint not null default 0 check (cached_input_tokens >= 0),
  request_count bigint not null default 0 check (request_count >= 0),
  source_key text not null,
  observed_at timestamptz not null default now(),
  check (period_end > period_start)
);

create unique index usage_buckets_source_unique
on public.usage_buckets (connection_id, period_start, period_end, model, source_key);

create index usage_buckets_connection_period_idx
on public.usage_buckets (connection_id, period_start desc);

create table public.cost_buckets (
  id bigint generated by default as identity primary key,
  connection_id uuid not null references public.provider_connections (id) on delete cascade,
  period_start timestamptz not null,
  period_end timestamptz not null,
  amount numeric(20, 8) not null check (amount >= 0),
  currency text not null default 'USD',
  cost_type public.usage_cost_type not null,
  line_item text not null default 'total',
  source_key text not null,
  observed_at timestamptz not null default now(),
  check (period_end > period_start),
  check (char_length(currency) = 3)
);

create unique index cost_buckets_source_unique
on public.cost_buckets (connection_id, period_start, period_end, line_item, source_key);

create index cost_buckets_connection_period_idx
on public.cost_buckets (connection_id, period_start desc);

create table public.usage_limits (
  id bigint generated by default as identity primary key,
  connection_id uuid not null references public.provider_connections (id) on delete cascade,
  metric_key text not null,
  label text not null,
  kind text not null,
  unit text not null,
  scope text not null,
  model text not null default 'all',
  window_name text,
  used numeric,
  limit_value numeric,
  remaining numeric,
  resets_at timestamptz,
  observed_at timestamptz not null default now(),
  check (used is null or used >= 0),
  check (limit_value is null or limit_value >= 0),
  check (remaining is null or remaining >= 0)
);

create unique index usage_limits_metric_unique
on public.usage_limits (connection_id, metric_key, model);

create table public.provider_sync_runs (
  id uuid primary key default gen_random_uuid(),
  connection_id uuid not null references public.provider_connections (id) on delete cascade,
  status text not null check (status in ('running', 'succeeded', 'failed')),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  error text
);

create index provider_sync_runs_connection_started_idx
on public.provider_sync_runs (connection_id, started_at desc);

create unique index provider_sync_runs_one_running_unique
on public.provider_sync_runs (connection_id)
where status = 'running';

