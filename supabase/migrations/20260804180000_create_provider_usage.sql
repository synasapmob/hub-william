create or replace function public.store_provider_credential(
  p_connection_id uuid,
  p_credential_kind text,
  p_ciphertext text,
  p_initialization_vector text,
  p_expires_at timestamptz default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  insert into private.provider_credentials (
    connection_id,
    credential_kind,
    ciphertext,
    initialization_vector,
    expires_at
  )
  values (
    p_connection_id,
    p_credential_kind,
    p_ciphertext,
    p_initialization_vector,
    p_expires_at
  )
  on conflict (connection_id) do update
  set credential_kind = excluded.credential_kind,
      ciphertext = excluded.ciphertext,
      initialization_vector = excluded.initialization_vector,
      expires_at = excluded.expires_at,
      updated_at = now();
end;
$$;

create or replace function public.read_provider_credential(p_connection_id uuid)
returns table (
  credential_kind text,
  ciphertext text,
  initialization_vector text,
  expires_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  return query
  select
    credential.credential_kind,
    credential.ciphertext,
    credential.initialization_vector,
    credential.expires_at
  from private.provider_credentials as credential
  where credential.connection_id = p_connection_id;
end;
$$;

create or replace function public.delete_provider_credential(p_connection_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  delete from private.provider_credentials
  where connection_id = p_connection_id;
end;
$$;

create or replace function public.store_provider_oauth_state(
  p_state_hash text,
  p_owner_id uuid,
  p_provider public.ai_provider,
  p_project_id text,
  p_redirect_to text,
  p_code_verifier text,
  p_history_starts_at timestamptz,
  p_expires_at timestamptz
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  delete from private.provider_oauth_states
  where expires_at <= now();

  insert into private.provider_oauth_states (
    state_hash,
    owner_id,
    provider,
    project_id,
    redirect_to,
    code_verifier,
    history_starts_at,
    expires_at
  )
  values (
    p_state_hash,
    p_owner_id,
    p_provider,
    p_project_id,
    p_redirect_to,
    p_code_verifier,
    p_history_starts_at,
    p_expires_at
  );
end;
$$;

create or replace function public.consume_provider_oauth_state(p_state_hash text)
returns table (
  owner_id uuid,
  provider public.ai_provider,
  project_id text,
  redirect_to text,
  code_verifier text,
  history_starts_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service role required';
  end if;

  return query
  delete from private.provider_oauth_states as oauth_state
  where oauth_state.state_hash = p_state_hash
    and oauth_state.expires_at > now()
  returning
    oauth_state.owner_id,
    oauth_state.provider,
    oauth_state.project_id,
    oauth_state.redirect_to,
    oauth_state.code_verifier,
    oauth_state.history_starts_at;
end;
$$;

