/* 
  how to use?:
    node scripts/check-tailwind-canonical.mjs app --write
    node scripts/check-tailwind-canonical.mjs app
*/

import { access, readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { __unstable__loadDesignSystem } from "tailwindcss";

const argumentsList = process.argv.slice(2);
const shouldWrite = argumentsList.includes("--write");
const sourceRoot =
  argumentsList.find((argument) => !argument.startsWith("--")) ?? "app";
const stylesheetCandidates = [
  join(sourceRoot, "styles.css"),
  join(sourceRoot, "styles", "index.css"),
  join("public", "css", "index.css"),
];
const stylesheetPath = await stylesheetCandidates.reduce(
  async (foundPath, candidatePath) => {
    const resolvedPath = await foundPath;

    if (resolvedPath) return resolvedPath;

    try {
      await access(candidatePath);
      return candidatePath;
    } catch {
      return undefined;
    }
  },
  Promise.resolve(undefined),
);

if (!stylesheetPath) {
  throw new Error(
    `Could not find a Tailwind stylesheet. Checked: ${stylesheetCandidates.join(", ")}`,
  );
}

const tailwindPath = join(process.cwd(), "node_modules/tailwindcss/index.css");
const stylesheet = await readFile(stylesheetPath, "utf8");
const designSystem = await __unstable__loadDesignSystem(stylesheet, {
  base: process.cwd(),
  loadStylesheet: async () => ({
    path: tailwindPath,
    base: process.cwd(),
    content: await readFile(tailwindPath, "utf8"),
  }),
  // This stylesheet declares `@plugin "@tailwindcss/typography"`, so the design
  // system has to be able to import it. Without this the loader throws
  // "No `loadModule` function provided to `compile`" before checking anything.
  loadModule: async (id, base) => {
    const imported = await import(id);

    return { path: id, base, module: imported.default ?? imported };
  },
});

/*
  `components/ui` is generated by `shadcn add`, which rewrites those files from
  components.json. Canonicalising a class list there is undone by the next run
  and shows up as a diff nobody wrote, so the walk skips it — the same reason
  that folder is exempt from the project's other class rules.
*/
const IGNORED_DIRECTORIES = new Set(["ui", "node_modules"]);

async function walk(directory) {
  const paths = [];

  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);

    if (entry.isDirectory() && IGNORED_DIRECTORIES.has(entry.name)) {
      continue;
    }

    if (entry.isDirectory()) {
      paths.push(...(await walk(path)));
    } else if (/\.(css|tsx?)$/.test(entry.name)) {
      paths.push(path);
    }
  }

  return paths;
}

let issueCount = 0;

for (const file of await walk(sourceRoot)) {
  const source = await readFile(file, "utf8");
  const lines = source.split("\n");

  for (const [lineIndex, line] of lines.entries()) {
    lines[lineIndex] = line.replace(
      /(["'`])([^"'`]*?)\1/g,
      (match, quote, raw) => {
        if (!/[a-z][a-z0-9-]*(?:\[|\/|-)/i.test(raw) || raw.includes("${")) {
          return match;
        }

        // A class list has no escaped newlines. Prose does, and prose is what
        // the loose test above lets through: `"…point\n- Second…"` matches it
        // on the `n-` of the escape, and reordering that silently rewrites the
        // sentence.
        if (raw.includes("\\n")) return match;

        const input = raw.trim().split(/\s+/).filter(Boolean);

        // Only touch a string every token of which the design system actually
        // knows. Unknown tokens still get sorted, which is how a paragraph
        // ends up shuffled; requiring all of them to resolve is what tells a
        // class list apart from a sentence that happens to contain a hyphen.
        if (
          designSystem
            .getClassOrder(input)
            .some(([, position]) => position === null)
        ) {
          return match;
        }
        const output = designSystem.canonicalizeCandidates(input, {
          rem: 16,
          collapse: true,
          logicalToPhysical: true,
        });

        if (output.length === 0 || output.join(" ") === input.join(" ")) {
          return match;
        }

        issueCount += 1;

        if (!shouldWrite) {
          console.error(
            `${file}:${lineIndex + 1}\n  ${input.join(" ")}\n  ${output.join(" ")}`,
          );
        }

        return `${quote}${output.join(" ")}${quote}`;
      },
    );
  }

  if (shouldWrite) {
    await writeFile(file, lines.join("\n"));
  }
}

if (issueCount > 0 && !shouldWrite) {
  console.error(
    `Found ${issueCount} non-canonical Tailwind class list${issueCount === 1 ? "" : "s"}.`,
  );
  process.exitCode = 1;
}
